def cmd(kind):
    s = ['<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 150 150" width="150" height="150" font-family="Noto Sans CJK KR" font-size="9">']
    s.append('<line x1="25" y1="130" x2="145" y2="130" stroke="#000"/><line x1="25" y1="130" x2="25" y2="5" stroke="#000"/>')
    s.append('<text x="85" y="145" text-anchor="middle">B − V (색지수)</text><text x="10" y="70" transform="rotate(-90 10 70)" text-anchor="middle">V (밝음 ↑)</text>')
    import random
    random.seed(3 if kind == 'a' else 5)
    pts = []
    if kind == 'a':  # 산개성단: 주계열이 위까지
        for i in range(70):
            t = random.random(); pts.append((30 + 100 * t, 12 + 110 * t + random.uniform(-4, 4)))
    else:  # 구상성단: 전향점 + 적색거성 + 수평가지
        for i in range(55):
            t = random.random(); pts.append((80 + 50 * t, 70 + 55 * t + random.uniform(-3, 3)))
        for i in range(30):
            t = random.random(); pts.append((80 + 45 * t, 70 - 55 * t + random.uniform(-3, 3)))
        for i in range(18):
            t = random.random(); pts.append((40 + 45 * t, 45 + random.uniform(-3, 3)))
    for x, y in pts:
        s.append(f'<circle cx="{x:.1f}" cy="{y:.1f}" r="1.3" fill="#000"/>')
    s.append('</svg>')
    return ''.join(s)
