# 회전 곡선
def rot_obs(r):
    return 230 * (1 - math.exp(-r / 2.0)) + 2 * r
def rot_kep(r):
    return rot_obs(r) if r <= 8 else rot_obs(8) * math.sqrt(8 / r)
