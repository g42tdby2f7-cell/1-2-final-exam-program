def gel(lanes, ladder=None, w=260, h=170, title='', bandw=34, ymin_log=None):
    """lanes: [(label, [(y_frac, thick), ...])]  y_frac 0(위)~1(아래). ladder: [(y_frac, 'label')]"""
    L = 60 if ladder else 20
    lw = (w - L - 10) / len(lanes)
    s = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w} {h}" width="{w}" height="{h}" font-family="Noto Sans CJK KR" font-size="10">']
    top, bot = 28, h - 10
    s.append(f'<rect x="{L-6}" y="{top-6}" width="{w-L-4}" height="{bot-top+6}" fill="#f4f4f4" stroke="#000"/>')
    for i, (lab, bands) in enumerate(lanes):
        cx = L + lw * i + lw / 2
        s.append(f'<text x="{cx:.1f}" y="14" text-anchor="middle">{lab}</text>')
        s.append(f'<rect x="{cx-bandw/2:.1f}" y="{top-4}" width="{bandw}" height="4" fill="#fff" stroke="#000" stroke-width="0.6"/>')
        for (yf, th) in bands:
            y = top + yf * (bot - top - 6)
            s.append(f'<rect x="{cx-bandw/2+2:.1f}" y="{y:.1f}" width="{bandw-4}" height="{th}" fill="#111"/>')
    if ladder:
        for (yf, lab) in ladder:
            y = top + yf * (bot - top - 6)
            s.append(f'<line x1="{L-10}" y1="{y+1:.1f}" x2="{L-4}" y2="{y+1:.1f}" stroke="#000"/>')
            s.append(f'<text x="{L-12}" y="{y+4:.1f}" text-anchor="end" font-size="9">{lab}</text>')
    s.append('</svg>')
    return ''.join(s)

